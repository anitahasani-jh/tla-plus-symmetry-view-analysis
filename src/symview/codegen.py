"""Generate TLC reduction artifacts without touching the original specification.

TLC attaches a reduction through the *configuration*, and both directives need an
operator that lives in the specification's context:

* ``SYMMETRY Perms`` expects an operator whose value is a set of permutations;
* ``VIEW ViewOp`` expects a *zero-argument* operator.

The public specifications must not be edited (the experiment has to compare the
same model under different reductions), so SymView writes a wrapper module that
extends the original and defines both operators, plus one configuration per
experimental arm.  The wrapper is a normal TLA+ module and is kept in the
replication package as evidence.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .analysis.history import HistoryProposal
from .analysis.program import SpecProgram
from .analysis.symmetry import SymmetryProposal

ARMS = ("plain", "symmetry", "view", "both", "manual")
SYMMETRY_VIEW_RE = re.compile(r"^\s*(SYMMETRY|VIEW)\b.*$", re.IGNORECASE)
BANNER = "-" * 76


@dataclass
class GeneratedArtifacts:
    wrapper_module: str = ""
    wrapper_text: str = ""
    configs: dict[str, str] = field(default_factory=dict)
    files: dict[str, str] = field(default_factory=dict)
    applicable: dict[str, bool] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"wrapper_module": self.wrapper_module,
                "wrapper_text": self.wrapper_text,
                "configs": self.configs,
                "applicable": self.applicable,
                "notes": self.notes}


def strip_reduction_directives(config_text: str) -> tuple[str, list[str]]:
    """Remove SYMMETRY/VIEW lines, returning the removed lines for the record."""
    removed = []
    kept = []
    for line in config_text.splitlines():
        if SYMMETRY_VIEW_RE.match(line):
            removed.append(line.strip())
        else:
            kept.append(line)
    return "\n".join(kept).rstrip() + "\n", removed


def build_wrapper(module: str, symmetry: SymmetryProposal,
                  history: HistoryProposal, version: str = "1.0.0") -> str:
    lines = [
        f"{BANNER[:-5]} MODULE {module}_SymView " + "-" * 5,
        "(***************************************************************************)",
        "(* GENERATED BY SymView " + version + " -- DO NOT EDIT.                            *)",
        "(*                                                                         *)",
        "(* This wrapper only exists so that a TLC configuration can refer to a      *)",
        "(* symmetry operator and a view operator.  The original specification is   *)",
        "(* extended, never modified, so every arm of the experiment checks exactly *)",
        "(* the same model.                                                         *)",
        "(***************************************************************************)",
        f"EXTENDS {module}, TLC",
        "",
    ]
    if symmetry.selected:
        perms = " \\cup ".join(f"Permutations({name})" for name in symmetry.selected)
        lines += [
            "(* Symmetry set proposed by SymView: the constants whose values are sets "
            "of model values,",
            "   used only through permutation-equivariant operators, and not "
            "distinguished by any",
            "   other constant.  TLC requires a set of permutations, hence the "
            "Permutations calls. *)",
            f"SymViewPerms == {perms}",
            "",
        ]
    if history.accepted:
        lines += [
            "(* View proposed by SymView: the variables that are observable or can "
            "influence an",
            "   observable variable.  The dropped ones are pure history.  TLC "
            "requires a",
            "   zero-argument view operator, hence the tuple of current values. *)",
            f"SymViewView == <<{', '.join(history.retained)}>>",
            "",
        ]
    lines += ["=" * 77]
    return "\n".join(lines) + "\n"


def generate(program: SpecProgram, symmetry: SymmetryProposal,
             history: HistoryProposal, allow_liveness: bool = False,
             version: str = "1.0.0") -> GeneratedArtifacts:
    ctx = program.ctx
    module = ctx.module_name
    artifacts = GeneratedArtifacts()
    original = ctx.cfg_path.read_text(encoding="utf-8", errors="replace")
    base, removed = strip_reduction_directives(original)
    if removed:
        artifacts.notes.append(
            "the shipped configuration already contained " + ", ".join(removed)
            + "; it is removed for the plain baseline and kept for the manual arm")

    sym_ok = bool(symmetry.selected) and (allow_liveness or not program.liveness)
    view_ok = history.accepted
    if symmetry.selected and program.liveness and not allow_liveness:
        artifacts.notes.append(
            "SYMMETRY is not emitted because the model checks a temporal property "
            "or assumes fairness; pass --allow-symmetry-with-liveness to override")
    if not symmetry.selected:
        artifacts.notes.append("no symmetry set was certified for this model")
    if not history.accepted:
        artifacts.notes.append("no view abstraction was certified for this model")

    artifacts.applicable = {"plain": True, "symmetry": sym_ok, "view": view_ok,
                            "both": sym_ok and view_ok,
                            "manual": bool(ctx.cfg.symmetry or ctx.cfg.view)}
    needs_wrapper = sym_ok or view_ok
    if needs_wrapper:
        artifacts.wrapper_module = f"{module}_SymView"
        artifacts.wrapper_text = build_wrapper(
            module, symmetry if sym_ok else SymmetryProposal(),
            history if view_ok else HistoryProposal(), version=version)
        artifacts.files[f"{module}_SymView.tla"] = artifacts.wrapper_text

    def config_for(symmetry_on: bool, view_on: bool) -> str:
        text = base
        extra = []
        # Unqualified names: every arm runs the wrapper module, which EXTENDS the
        # original specification, so the operators are in scope and the only
        # difference between arms is this directive.
        if symmetry_on:
            extra.append("SYMMETRY SymViewPerms")
        if view_on:
            extra.append("VIEW SymViewView")
        if extra:
            text = text.rstrip() + "\n" + "\n".join(extra) + "\n"
        return text

    for arm in ("plain", "symmetry", "view", "both"):
        if not artifacts.applicable[arm]:
            continue
        text = config_for(arm in ("symmetry", "both"), arm in ("view", "both"))
        artifacts.configs[arm] = text
        artifacts.files[f"{module}_SymView_{arm}.cfg"] = text
    if artifacts.applicable["manual"]:
        artifacts.configs["manual"] = original
        artifacts.files[f"{module}_SymView_manual.cfg"] = original
    return artifacts


def write_artifacts(artifacts: GeneratedArtifacts, target_dir) -> list[str]:
    """Write the generated files; returns the file names written."""
    from pathlib import Path
    target = Path(target_dir)
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in artifacts.files.items():
        (target / name).write_text(text, encoding="utf-8")
        written.append(name)
    return written
