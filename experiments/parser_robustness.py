#!/usr/bin/env python3
"""Measure how much of the corpus the SymView parser actually understands.

This is the robustness evidence for the analysis parser: for every ``.tla`` file
in the corpus it records token coverage (every token must be accounted for by
some AST node), the number of ``unknown`` fallback nodes and the number of
unlexable characters.  Results are written as raw JSON plus a Markdown table; no
number in the report is typed by hand.

    python experiments/parser_robustness.py
"""

from __future__ import annotations

import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import yaml  # noqa: E402

from symview.parse_tla import parse_file  # noqa: E402
from symview.util import ensure_utf8_stdio, write_json, write_text  # noqa: E402

RAW = ROOT / "results" / "raw" / "parser_robustness.json"
TABLE = ROOT / "analysis" / "output" / "tables" / "parser_robustness.md"


def collect() -> list[Path]:
    files: list[Path] = []
    for base in (ROOT / "benchmarks" / "public", ROOT / "benchmarks" / "lab"):
        if base.exists():
            files += sorted(base.rglob("*.tla"))
    return files


def main() -> int:
    ensure_utf8_stdio()
    files = collect()
    rows = []
    reason_counter: collections.Counter[str] = collections.Counter()
    for path in files:
        try:
            ast, lex, stats = parse_file(path)
        except Exception as exc:  # a crash here is itself a finding
            rows.append({"file": str(path.relative_to(ROOT)).replace("\\", "/"),
                         "module": None, "exception": f"{type(exc).__name__}: {exc}",
                         "coverage": 0.0, "unknown_nodes": -1, "bad_tokens": -1,
                         "tokens": 0})
            continue
        for node in ast.walk():
            if node.kind == "unknown":
                reason_counter[node.text] += 1
        rows.append({
            "file": str(path.relative_to(ROOT)).replace("\\", "/"),
            "module": stats["module"],
            "tokens": stats["cov_total_tokens"],
            "coverage": round(stats["cov_coverage"], 6),
            "unknown_nodes": stats["unknown_nodes"],
            "bad_tokens": stats["bad_tokens"],
            "uncovered_tokens": len(stats["cov_uncovered_tokens"]),
            "unknown_tokens": stats["cov_unknown_tokens"],
            "proof_tokens_skipped": stats["proof_tokens_skipped"],
            "parser_notes": stats["parser_notes"],
            "exception": None,
        })

    total_files = len(rows)
    crashed = [r for r in rows if r["exception"]]
    perfect = [r for r in rows if not r["exception"] and r["unknown_nodes"] == 0
               and r["bad_tokens"] == 0 and r["uncovered_tokens"] == 0]
    clean_coverage = [r for r in rows if not r["exception"] and r["uncovered_tokens"] == 0]
    token_sum = sum(r["tokens"] for r in rows)
    covered = sum(int(r["tokens"] * r["coverage"]) for r in rows if not r["exception"])
    summary = {
        "files": total_files,
        "files_crashed": len(crashed),
        "files_perfect_ast": len(perfect),
        "files_full_token_coverage": len(clean_coverage),
        "tokens": token_sum,
        "tokens_covered": covered,
        "token_coverage": round(covered / token_sum, 6) if token_sum else 1.0,
        "unknown_nodes_total": sum(max(0, r["unknown_nodes"]) for r in rows),
        "bad_tokens_total": sum(max(0, r["bad_tokens"]) for r in rows),
        "unknown_reasons": dict(reason_counter.most_common()),
    }
    write_json(RAW, {"summary": summary, "files": rows})

    lines = [
        "# Parser robustness over the corpus",
        "",
        "Generated by `experiments/parser_robustness.py`; do not edit by hand.",
        "",
        f"- `.tla` files parsed: **{summary['files']}**",
        f"- files that crashed the parser: **{summary['files_crashed']}**",
        f"- files with 100% token coverage: **{summary['files_full_token_coverage']}** "
        f"({100.0 * summary['files_full_token_coverage'] / max(1, total_files):.1f}%)",
        f"- files parsed with no `unknown` fallback node: **{summary['files_perfect_ast']}** "
        f"({100.0 * summary['files_perfect_ast'] / max(1, total_files):.1f}%)",
        f"- corpus tokens: **{summary['tokens']}**, covered by the AST: "
        f"**{summary['tokens_covered']}** ({100.0 * summary['token_coverage']:.3f}%)",
        f"- `unknown` fallback nodes: **{summary['unknown_nodes_total']}**",
        f"- unlexable characters: **{summary['bad_tokens_total']}**",
        "",
        "## Fallback reasons",
        "",
        "| Reason | Count |", "|---|---|",
    ]
    for reason, count in reason_counter.most_common(15):
        lines.append(f"| `{reason}` | {count} |")
    lines += ["", "## Files needing the most fallbacks", "",
              "| File | Tokens | Coverage | unknown | notes |", "|---|---|---|---|---|"]
    worst = sorted((r for r in rows if not r["exception"]),
                   key=lambda r: -r["unknown_nodes"])[:15]
    for row in worst:
        lines.append(f"| `{row['file']}` | {row['tokens']} | {row['coverage']:.4f} | "
                     f"{row['unknown_nodes']} | {row['parser_notes']} |")
    if crashed:
        lines += ["", "## Crashes", ""]
        lines += [f"- `{r['file']}`: {r['exception']}" for r in crashed]
    lines.append("")
    write_text(TABLE, "\n".join(lines))

    print(f"files={summary['files']} crashed={summary['files_crashed']} "
          f"full_coverage={summary['files_full_token_coverage']} "
          f"perfect={summary['files_perfect_ast']} "
          f"token_coverage={summary['token_coverage']:.4f} "
          f"unknowns={summary['unknown_nodes_total']} bad={summary['bad_tokens_total']}")
    print(f"[ok] {RAW.relative_to(ROOT)}")
    print(f"[ok] {TABLE.relative_to(ROOT)}")
    return 0 if not crashed else 1


if __name__ == "__main__":
    raise SystemExit(main())
